// Precalculated verdict assessments (engineering plan §4.2): per item, every half-month window as the engine and
// the app's views see it, written by `npm run data:build` to generated/assessments/ and committed, so verdict
// changes are reviewable as diffs. Deterministic: a fixed year, no clock, stable ordering.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { Document, isScalar, isSeq, visit } from "yaml";
import { itemView } from "../src/app/item-view";
import { todayView, windowPhrase } from "../src/app/today-view";
import type { AppData, AppItem } from "../src/shared/app-data";
import { WINDOW_COUNT, windowLabel } from "../src/shared/time";
import {
  evaluate,
  type LevelSet,
  type Levels,
  type Marker,
  type Reason,
  typicalLevels,
  typicalOutlook,
  type Verdict,
  type VerdictResult,
} from "../src/shared/verdict";

export const ASSESSMENTS_DIR = "generated/assessments";
/** Window dates use this year, so the output never depends on the day it is built. */
export const ASSESSMENT_YEAR = 2026;
export const HEADER =
  "Generated by `npm run data:build` from `content/`, `data/` and the verdict engine. Do not edit.";

const LETTER: Record<Verdict, string> = { peak: "P", good: "G", skip: "S", limited: "·" };
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const dateOf = (w: number) => ({
  year: ASSESSMENT_YEAR,
  month: Math.floor(w / 2) + 1,
  day: w % 2 === 0 ? 1 : 16,
});
const iso = (w: number) => {
  const d = dateOf(w);
  return `${d.year}-${String(d.month).padStart(2, "0")}-${String(d.day).padStart(2, "0")}`;
};

function reasonText(r: Reason): string {
  switch (r.code) {
    case "rated":
      return `rated ${r.rating} (${r.variety ? `variety ${r.variety}` : `origin ${r.origin}`})`;
    case "origin-unrated":
      return `origin-unrated ${r.origin}`;
    case "variety-unrated":
      return `variety-unrated ${r.variety}`;
    case "typical-origin-poor":
    case "far-origin":
      return `${r.code} ${r.origin}`;
    case "selection":
      return `selection ${r.selection}`;
    case "look-for":
      return `look-for ${r.origins.join(", ")}`;
    case "main-peak":
      return `main-peak ${windowLabel(r.from)} to ${windowLabel(r.to)}`;
    default:
      return r.code;
  }
}

function markerText(m: Marker): string {
  if (m.kind === "last-call") return `last-call (fades by ${windowLabel(m.fadesBy)})`;
  if (m.kind === "improves") return `improves (${windowLabel(m.window)})`;
  return m.kind;
}

function levelSet(set: LevelSet, levels: Levels, availableShare: number, lookForShare: number) {
  const why =
    set.available === "share"
      ? `yes: counted share ${pct(set.countedShare)} ≥ ${pct(availableShare)}`
      : set.available === "in-stores"
        ? `yes: cited in stores (${set.origins
            .filter((o) => o.counts && o.inStores)
            .map((o) => o.origin)
            .join(", ")})`
        : set.origins.length === 0
          ? "no: no origin at this level"
          : `no: counted share ${pct(set.countedShare)} < ${pct(availableShare)}, none cited in stores`;
  return {
    share: pct(set.share),
    available: why,
    "whole bin":
      set.share > lookForShare + 1e-9 ? `yes (> ${pct(lookForShare)})` : `no (≤ ${pct(lookForShare)})`,
    origins: set.origins.map(
      (o) =>
        `${o.origin} ${o.rating} ${levels.total > 0 ? pct(o.weight / levels.total) : "0.0%"}` +
        `${o.counts ? "" : " (low confidence, not counted)"}${o.inStores ? " (cited in stores)" : ""}`,
    ),
  };
}

function decider(item: AppItem, r: VerdictResult, w: number) {
  const rated = r.reasons.find((x) => x.code === "rated");
  if (rated?.code !== "rated") return null;
  const series = rated.variety
    ? item.inputs.varieties.find((v) => v.id === rated.variety)
    : item.inputs.origins[rated.origin ?? ""];
  return {
    [rated.variety ? "variety" : "origin"]: rated.variety ?? rated.origin,
    rating: rated.rating,
    evidence: series?.evidence?.[w] ?? "none",
  };
}

interface Row {
  item: string;
  window: string;
  date: string;
  verdict: Verdict;
  basis: string;
  decider: string;
  rating: string;
  evidence: string;
  confidence: string;
  peakShare: string;
  peakAvailable: string;
  goodShare: string;
  goodAvailable: string;
  lookFor: string;
  today: string;
  todayLine: string;
}

type TodayCards = {
  section: "best right now" | "good buys";
  card: ReturnType<typeof todayView>["best"][number];
};

function assessItem(app: AppData, item: AppItem, today: Map<string, TodayCards>[]) {
  const { rules } = app.env;
  const outlook = typicalOutlook(item.inputs, app.env, ASSESSMENT_YEAR);
  const byVariety = item.inputs.varieties.length > 0;
  const rows: Row[] = [];
  const windows: Record<string, unknown> = {};
  for (let w = 0; w < WINDOW_COUNT; w++) {
    const date = dateOf(w);
    const r = evaluate(item.inputs, { date }, app.env);
    const levels = byVariety ? null : typicalLevels(item.inputs, { date }, app.env);
    const basis = byVariety ? "variety" : r.selection !== null ? "selection" : "typical";
    const d = decider(item, r, w);
    const look = r.reasons.find((x) => x.code === "look-for");
    const main = r.reasons.find((x) => x.code === "main-peak");
    const t = today[w]?.get(item.inputs.id);
    const entry: Record<string, unknown> = {
      when: `${windowPhrase(w)} (from ${iso(w)})`,
      verdict: r.verdict,
      rule: r.ruleFired,
      basis,
      ...(r.selection !== null ? { selection: r.selection } : {}),
      decided: d ?? "none",
    };
    if (levels) {
      entry.weights = levels.weights;
      entry.typical = levels.typical.map(
        (o) =>
          `${o.origin} ${o.rating ?? "unrated"} ${levels.total > 0 ? pct(o.weight / levels.total) : "0.0%"}` +
          (o.supply === null
            ? ""
            : ` (supply ${o.supply.toFixed(2)}${o.supply < rules.supplyIndex.thin ? ", thin" : ""})`),
      );
      entry.peak = levelSet(levels.peak, levels, rules.availableShare, rules.lookForShare);
      entry.good = levelSet(levels.good, levels, rules.availableShare, rules.lookForShare);
    }
    entry["look for"] = look?.code === "look-for" ? look.origins : [];
    entry["label note"] = r.labelNote;
    entry.reasons = r.reasons.map(reasonText);
    entry.confidence =
      r.weakProperties.length === 0 ? r.confidence : `${r.confidence} (${r.weakProperties.join(", ")})`;
    entry.markers = r.markers.map(markerText);
    if (main?.code === "main-peak")
      entry["main peak"] =
        `rated Peak here, but Peak is kept for ${windowLabel(main.from)} to ${windowLabel(main.to)} (P19), so ${r.verdict}`;
    entry.today = t
      ? {
          section: t.section,
          line: t.card.varietyLine ?? "none",
          reason: t.card.reason ?? "none",
          origin: t.card.origin ?? "none",
          avoid: t.card.avoid ?? "none",
          tags: t.card.tags,
        }
      : "not on Today";
    if (byVariety) {
      const view = itemView(app, item.inputs.id, date);
      entry.varieties = Object.fromEntries(
        (view?.varietySummary ?? []).map((g) => [g.verdict ?? "not in stores", g.names]),
      );
    }
    windows[windowLabel(w)] = entry;
    rows.push({
      item: item.inputs.id,
      window: windowLabel(w),
      date: iso(w),
      verdict: r.verdict,
      basis,
      decider: d ? String(d.origin ?? d.variety) : "",
      rating: d?.rating ?? "",
      evidence: d ? String(d.evidence) : "",
      confidence: r.confidence,
      peakShare: levels ? pct(levels.peak.share) : "",
      peakAvailable: levels ? (levels.peak.available ?? "no") : "",
      goodShare: levels ? pct(levels.good.share) : "",
      goodAvailable: levels ? (levels.good.available ?? "no") : "",
      lookFor: look?.code === "look-for" ? look.origins.join(" ") : "",
      today: t?.section ?? "",
      todayLine: t?.card.varietyLine ?? "",
    });
  }
  const doc = {
    item: item.inputs.id,
    name: item.name,
    status: item.status,
    "rated by": byVariety ? "variety" : "origin",
    "peak worth seeking": item.inputs.peakWorthSeeking,
    "always good": item.inputs.alwaysGood,
    outlook: `${outlook.map((v) => LETTER[v]).join("")} (Jan to Dec, two windows a month: P Peak, G Good, S Skip, · Limited evidence)`,
    windows,
  };
  return { yaml: toYaml(doc), rows };
}

/** Block YAML, with lists of plain values on one line so each window reads compactly and diffs by line. */
function toYaml(value: unknown): string {
  const doc = new Document(value);
  visit(doc, {
    Seq(_, node) {
      if (isSeq(node) && node.items.every((i) => isScalar(i))) node.flow = true;
    },
  });
  doc.commentBefore = ` ${HEADER}`;
  return doc.toString({ lineWidth: 0, flowCollectionPadding: false });
}

const csvCell = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);

/** Every assessment file by name: one YAML file per non-synthetic item and index.csv. */
export function renderAssessments(app: AppData): Map<string, string> {
  const today = Array.from({ length: WINDOW_COUNT }, (_, w) => {
    const view = todayView(app, dateOf(w));
    const m = new Map<string, TodayCards>();
    for (const card of view.best) m.set(card.id, { section: "best right now", card });
    for (const card of view.good) m.set(card.id, { section: "good buys", card });
    return m;
  });
  const files = new Map<string, string>();
  const rows: Row[] = [];
  const items = app.items.filter((i) => !i.synthetic).sort((a, b) => a.inputs.id.localeCompare(b.inputs.id));
  for (const item of items) {
    const a = assessItem(app, item, today);
    files.set(`${item.inputs.id}.yaml`, a.yaml);
    rows.push(...a.rows);
  }
  const columns = Object.keys(rows[0] ?? { item: "" }) as (keyof Row)[];
  const csv = [
    `# ${HEADER}`,
    columns.join(","),
    ...rows.map((r) => columns.map((c) => csvCell(String(r[c]))).join(",")),
  ];
  files.set("index.csv", `${csv.join("\n")}\n`);
  return files;
}

/** Files that differ from a fresh build: changed, missing, or not produced by it. */
export function drift(dir: string, files: ReadonlyMap<string, string>): string[] {
  const out: string[] = [];
  const present = existsSync(dir) ? readdirSync(dir).sort() : [];
  for (const [name, content] of files) {
    const path = join(dir, name);
    if (!present.includes(name)) out.push(`${name}: missing`);
    else if (readFileSync(path, "utf8") !== content) out.push(`${name}: differs`);
  }
  for (const name of present) if (!files.has(name)) out.push(`${name}: not produced by the build`);
  return out;
}
